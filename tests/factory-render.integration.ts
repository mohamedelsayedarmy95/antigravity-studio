import assert from "node:assert/strict";
import { execFileSync, spawn, spawnSync } from "node:child_process";
import { once } from "node:events";
import { mkdtemp, readFile, readdir, rm, unlink, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { test } from "node:test";

const root = path.resolve(import.meta.dirname, "..");
const ffmpeg = (...args: string[]) => execFileSync("ffmpeg", ["-nostdin", "-v", "error", "-filter_threads", "1", ...args]);
function factory(...args: string[]) {
  const result = spawnSync(process.execPath, ["--import", "tsx", "scripts/factory.ts", ...args], {
    cwd: root, encoding: "utf8", timeout: 120000, windowsHide: true,
  });
  if (result.error) throw result.error;
  return { code: result.status, output: result.stdout + result.stderr };
}

test("local screen stills are repeatable and render rejects invalid or unreadable sources", async (t) => {
  const temp = await mkdtemp(path.join(tmpdir(), "factory render test "));
  t.after(() => rm(temp, { recursive: true, force: true }));
  const project = path.join(temp, "render-test");
  const out = path.join(temp, "reports");
  const dirs = path.join(project, "assets", "screenshots");
  const briefFile = path.join(project, "brief.json");
  const home = path.join(dirs, "home.jpg");
  const clip = path.join(dirs, "feature.mp4");
  const created = factory("init", "--name", "render-test", "--parent", temp);
  assert.equal(created.code, 0, created.output);
  const render = () => factory("render", "--project", project, "--out", out, "--ratios", "16:9", "--frame", "37");
  const unapproved = render();
  assert.equal(unapproved.code, 1, unapproved.output);
  assert.match(unapproved.output, /renderRights declaration/);
  const brief = JSON.parse(await readFile(briefFile, "utf8"));
  Object.assign(brief, { fps: 30, durationSeconds: 6, renderRights: {
    origin: "synthetic", approved: true, license: "Generated by the local test", privacy: "Synthetic fixtures contain no private data",
  } });
  await writeFile(briefFile, JSON.stringify(brief));
  const missing = render();
  assert.equal(missing.code, 1, missing.output);
  assert.match(missing.output, /no-assets/);
  ffmpeg("-f", "lavfi", "-i", "color=blue:size=96x160:duration=1", "-frames:v", "1", "-threads", "1", home);
  await writeFile(clip, "broken fixture");
  const corrupt = render();
  assert.equal(corrupt.code, 1, corrupt.output);
  assert.match(corrupt.output, /invalid-media feature\.mp4/);
  await unlink(clip);
  const makeClip = (sar: string) => ffmpeg("-f", "lavfi", "-i", "testsrc2=size=192x128:rate=30:duration=1",
    "-vf", "setsar=" + sar, "-c:v", "mpeg4", "-threads", "1", clip);
  makeClip("2/1");
  const incompatible = render();
  assert.equal(incompatible.code, 1, incompatible.output);
  assert.match(incompatible.output, /requires square pixels/);
  await unlink(clip);
  makeClip("1");

  if (process.platform === "win32") {
    const holder = spawn("powershell.exe", ["-NoProfile", "-NonInteractive", "-Command",
      "$f=[IO.File]::Open($env:UVF_TEST_LOCK,'Open','Read','None'); 'locked'; [Console]::In.ReadLine() > $null; $f.Dispose()",
    ], { windowsHide: true, env: { ...process.env, UVF_TEST_LOCK: clip } });
    const done = once(holder, "close");
    try {
      const [data] = await once(holder.stdout, "data");
      assert.match(String(data), /locked/);
      const unavailable = render();
      assert.equal(unavailable.code, 1, unavailable.output);
      assert.match(unavailable.output, /unreadable-input feature\.mp4/);
    } finally {
      holder.stdin.end("\n");
      await done;
    }
  }
  await writeFile(briefFile, JSON.stringify({ ...brief, hook: "Stylish overlays with long headings ".repeat(6).trim() }));
  const overflow = factory("render", "--project", project, "--out", out, "--ratios", "1:1", "--frame", "18");
  assert.equal(overflow.code, 1, overflow.output);
  assert.match(overflow.output, /Copy exceeds the factory safe area/);
  await writeFile(briefFile, JSON.stringify(brief));
  assert.equal((await readdir(out)).filter((name) => name.startsWith("still-")).length, 0);
  for (let i = 0; i < 2; i++) {
    const actual = render();
    assert.equal(actual.code, 0, actual.output);
  }
  const outputs = (await readdir(out)).filter((name) => name.startsWith("still-"));
  assert.equal(outputs.length, 2);
  const captures = await Promise.all(outputs.map((name) => readFile(path.join(out, name, "render-test-16x9-f37.png"))));
  assert.ok(captures[0].equals(captures[1]), "independent still jobs should be byte-identical");
});
